-- Trigger

CREATE OR REPLACE TRIGGER HEI_SOURCE_BI
BEFORE INSERT ON HEI_SOURCE
FOR EACH ROW
WHEN (NEW.SOURCE_ID IS NULL)
BEGIN
  :NEW.SOURCE_ID := HEI_SOURCE_SEQ.NEXTVAL;
END;
