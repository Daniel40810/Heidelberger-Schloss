-- Lage der Bauwerke: Metadaten (WGS84, SRID 8307) und raeumlicher Index
BEGIN
  INSERT INTO USER_SDO_GEOM_METADATA (TABLE_NAME, COLUMN_NAME, DIMINFO, SRID)
  SELECT 'HEI_BUILDING', 'GEOM',
         SDO_DIM_ARRAY(SDO_DIM_ELEMENT('Longitude', -180, 180, 0.05),
                       SDO_DIM_ELEMENT('Latitude', -90, 90, 0.05)),
         8307
    FROM DUAL
   WHERE NOT EXISTS (SELECT 1 FROM USER_SDO_GEOM_METADATA
                      WHERE TABLE_NAME = 'HEI_BUILDING' AND COLUMN_NAME = 'GEOM');
  COMMIT;
END;
/

CREATE INDEX HEI_BUILDING_SX ON HEI_BUILDING (GEOM) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2
