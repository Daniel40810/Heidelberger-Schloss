CREATE TABLE HEI_EVENT (
  EVENT_ID        NUMBER(10)     NOT NULL,
  SESSION_ID      NUMBER(10)     NOT NULL,
  ZEIT            TIMESTAMP(6)   DEFAULT LOCALTIMESTAMP NOT NULL,
  SEKUNDE         NUMBER(8,1)    NOT NULL,
  ART             VARCHAR2(12)   NOT NULL,
  ZIEL            VARCHAR2(80 CHAR),
  WERT            VARCHAR2(200 CHAR),
  STUFE           NUMBER(1),
  STUNDE          NUMBER(5,2),
  CONSTRAINT HEI_EVENT_PK PRIMARY KEY (EVENT_ID),
  CONSTRAINT HEI_EVENT_SESSION_FK FOREIGN KEY (SESSION_ID) REFERENCES HEI_SESSION (SESSION_ID) ON DELETE CASCADE
)
/

-- Kommentare

COMMENT ON TABLE HEI_SOURCE IS 'Quellen: wer sagt was, mit Kernaussage, Massen und Beleg (nach SEM_SOURCE)'
/

COMMENT ON TABLE HEI_STAGE IS 'Die vier Zeitstufen: 1619, nach 1689, nach 1693, nach 1764'
/

COMMENT ON TABLE HEI_BUILDING IS 'Bauwerke mit Rolle, Detailstufe, Zeitstufen und Lage (lokal in Metern und als Punkt in WGS84)'
/

COMMENT ON TABLE HEI_CHRONIK IS 'Geschichtliche Ereignisse zum Schloss, je Zeitstufe, mit Quelle'
/

COMMENT ON TABLE HEI_VIEW IS 'Blickpunkte: Drehpunkt, Hoehe ueber dem Boden, Gier, Nick und Abstand der Orbit-Kamera'
/

COMMENT ON TABLE HEI_CLIP IS 'Fahrten (Kamera, im Programm berechnet) und das Drehbuch; hier nur der Katalog'
/

COMMENT ON TABLE HEI_SHOT IS 'Szenen des Drehbuchs: Tageszeit von bis, Nebel, Dunst'
/

COMMENT ON TABLE HEI_PANEL IS 'Tafeln einer Szene: Zeitfenster in Sekunden, Kopf, Text, Quelle'
/

COMMENT ON TABLE HEI_SESSION IS 'Eine Zeile je Programmstart: Rechner, Fenster, Dauer, Bilder pro Sekunde'
/

COMMENT ON TABLE HEI_STATE IS 'Zustand des Programms (Kamera, Zeit, Wetter, Schalter): AUTO beim Beenden, MANUELL von Hand gemerkt'
/

COMMENT ON TABLE HEI_EVENT IS 'Protokoll einer Sitzung: Start, Ende, Fehler, Fahrten, Zeitstufen, Einrichter'
/
