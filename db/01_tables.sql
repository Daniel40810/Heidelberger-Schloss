-- ============================================================================
-- Heidelberger Schloss, Phase 10: Tabellen mit dem Praefix HEI_ im Schema DEMO
-- Aufbau nach deinen SEM_-Tabellen (Semiramis): Praefix je Projekt, <TABELLE>_ID,
-- _PK / _UK / _FK / _CK je Tabelle. Jede Anweisung endet mit einer Zeile "/".
-- Das Skript kann mehrfach laufen: was es schon gibt, meldet der Einrichter als "vorhanden".
-- Reihenfolge: 01 Tabellen, 02 Folgen, Trigger, Indizes, 03 Paket HEI_API, 04 Grunddaten.
-- Zeichensatz: UTF-8.
-- ============================================================================

CREATE TABLE HEI_SOURCE (
  SOURCE_ID       NUMBER(10)     NOT NULL,
  CODE            VARCHAR2(30)   NOT NULL,
  AUTOR           VARCHAR2(80)   NOT NULL,
  LEBENSZEIT      VARCHAR2(60),
  WERK            VARCHAR2(160)  NOT NULL,
  STELLE          VARCHAR2(40),
  SPRACHE         VARCHAR2(40),
  UEBERLIEFERUNG  VARCHAR2(200),
  ABSTAND_JAHRE   NUMBER(5),
  BEZUG           VARCHAR2(10),
  KERNAUSSAGE     VARCHAR2(1000) NOT NULL,
  MASSE           VARCHAR2(400),
  BELEG           VARCHAR2(400),
  CONSTRAINT HEI_SOURCE_PK PRIMARY KEY (SOURCE_ID),
  CONSTRAINT HEI_SOURCE_UK UNIQUE (CODE)
)
/

CREATE TABLE HEI_STAGE (
  STAGE_ID        NUMBER(10)     NOT NULL,
  NR              NUMBER(2)      NOT NULL,
  JAHR            NUMBER(4)      NOT NULL,
  DATUM           DATE,
  NAME            VARCHAR2(60)   NOT NULL,
  KURZ            VARCHAR2(160)  NOT NULL,
  BESCHREIBUNG    VARCHAR2(1000),
  SOURCE_ID       NUMBER(10),
  CONSTRAINT HEI_STAGE_PK PRIMARY KEY (STAGE_ID),
  CONSTRAINT HEI_STAGE_UK UNIQUE (NR),
  CONSTRAINT HEI_STAGE_NR_CK CHECK (NR BETWEEN 0 AND 3),
  CONSTRAINT HEI_STAGE_SOURCE_FK FOREIGN KEY (SOURCE_ID) REFERENCES HEI_SOURCE (SOURCE_ID)
)
/

CREATE TABLE HEI_BUILDING (
  BUILDING_ID     NUMBER(10)     NOT NULL,
  CODE            VARCHAR2(30)   NOT NULL,
  NAME            VARCHAR2(80)   NOT NULL,
  NAME_HISTORISCH VARCHAR2(80),
  BEZUG           VARCHAR2(10)   NOT NULL,
  DETAIL          VARCHAR2(10)   NOT NULL,
  STUFEN          NUMBER(2)      DEFAULT 15 NOT NULL,
  ROLLE           VARCHAR2(400),
  X_M             NUMBER(9,2),
  Z_M             NUMBER(9,2),
  GEOM            SDO_GEOMETRY,
  SOURCE_ID       NUMBER(10),
  CONSTRAINT HEI_BUILDING_PK PRIMARY KEY (BUILDING_ID),
  CONSTRAINT HEI_BUILDING_UK UNIQUE (CODE),
  CONSTRAINT HEI_BUILDING_DETAIL_CK CHECK (DETAIL IN ('VOLL','MITTEL','EINFACH')),
  CONSTRAINT HEI_BUILDING_STUFEN_CK CHECK (STUFEN BETWEEN 0 AND 15),
  CONSTRAINT HEI_BUILDING_SOURCE_FK FOREIGN KEY (SOURCE_ID) REFERENCES HEI_SOURCE (SOURCE_ID)
)
/

CREATE TABLE HEI_CHRONIK (
  CHRONIK_ID      NUMBER(10)     NOT NULL,
  STAGE_ID        NUMBER(10)     NOT NULL,
  JAHR            NUMBER(4)      NOT NULL,
  DATUM           DATE,
  TITEL           VARCHAR2(80)   NOT NULL,
  TEXT            VARCHAR2(600)  NOT NULL,
  SOURCE_ID       NUMBER(10),
  CONSTRAINT HEI_CHRONIK_PK PRIMARY KEY (CHRONIK_ID),
  CONSTRAINT HEI_CHRONIK_UK UNIQUE (JAHR, TITEL),
  CONSTRAINT HEI_CHRONIK_STAGE_FK FOREIGN KEY (STAGE_ID) REFERENCES HEI_STAGE (STAGE_ID),
  CONSTRAINT HEI_CHRONIK_SOURCE_FK FOREIGN KEY (SOURCE_ID) REFERENCES HEI_SOURCE (SOURCE_ID)
)
/

CREATE TABLE HEI_VIEW (
  VIEW_ID         NUMBER(10)     NOT NULL,
  NR              NUMBER(3)      NOT NULL,
  NAME            VARCHAR2(60)   NOT NULL,
  NOTIZ           VARCHAR2(200),
  DREHPUNKT_X     NUMBER(9,2)    NOT NULL,
  DREHPUNKT_Z     NUMBER(9,2)    NOT NULL,
  HOEHE_UEBER_BODEN NUMBER(8,2)  NOT NULL,
  GIER_GRAD       NUMBER(8,2)    NOT NULL,
  NICK_GRAD       NUMBER(6,2)    NOT NULL,
  ABSTAND_M       NUMBER(8,2)    NOT NULL,
  INNEN           CHAR(1)        DEFAULT 'N' NOT NULL,
  CONSTRAINT HEI_VIEW_PK PRIMARY KEY (VIEW_ID),
  CONSTRAINT HEI_VIEW_UK UNIQUE (NR),
  CONSTRAINT HEI_VIEW_INNEN_CK CHECK (INNEN IN ('J','N'))
)
/

CREATE TABLE HEI_CLIP (
  CLIP_ID         NUMBER(10)     NOT NULL,
  CODE            VARCHAR2(30)   NOT NULL,
  ART             VARCHAR2(10)   NOT NULL,
  STUFE           NUMBER(1)      DEFAULT 0 NOT NULL,
  NR              NUMBER(3),
  NAME            VARCHAR2(80)   NOT NULL,
  INFO            VARCHAR2(400),
  DAUER_S         NUMBER(7,2),
  CONSTRAINT HEI_CLIP_PK PRIMARY KEY (CLIP_ID),
  CONSTRAINT HEI_CLIP_UK UNIQUE (CODE),
  CONSTRAINT HEI_CLIP_ART_CK CHECK (ART IN ('FAHRT','DREHBUCH')),
  CONSTRAINT HEI_CLIP_STUFE_CK CHECK (STUFE BETWEEN 0 AND 3)
)
/

CREATE TABLE HEI_SHOT (
  SHOT_ID         NUMBER(10)     NOT NULL,
  CLIP_ID         NUMBER(10)     NOT NULL,
  NR              NUMBER(3)      NOT NULL,
  NAME            VARCHAR2(80)   NOT NULL,
  STUNDE_VON      NUMBER(5,2)    NOT NULL,
  STUNDE_BIS      NUMBER(5,2)    NOT NULL,
  NEBEL           CHAR(1)        DEFAULT 'N' NOT NULL,
  DUNST           NUMBER(4,2)    DEFAULT 0.12 NOT NULL,
  SOURCE_ID       NUMBER(10),
  CONSTRAINT HEI_SHOT_PK PRIMARY KEY (SHOT_ID),
  CONSTRAINT HEI_SHOT_UK UNIQUE (CLIP_ID, NR),
  CONSTRAINT HEI_SHOT_NEBEL_CK CHECK (NEBEL IN ('J','N')),
  CONSTRAINT HEI_SHOT_STUNDE_CK CHECK (STUNDE_VON BETWEEN 0 AND 24 AND STUNDE_BIS BETWEEN 0 AND 24),
  CONSTRAINT HEI_SHOT_CLIP_FK FOREIGN KEY (CLIP_ID) REFERENCES HEI_CLIP (CLIP_ID) ON DELETE CASCADE,
  CONSTRAINT HEI_SHOT_SOURCE_FK FOREIGN KEY (SOURCE_ID) REFERENCES HEI_SOURCE (SOURCE_ID)
)
/

CREATE TABLE HEI_PANEL (
  PANEL_ID        NUMBER(10)     NOT NULL,
  SHOT_ID         NUMBER(10)     NOT NULL,
  VON_S           NUMBER(6,1)    NOT NULL,
  BIS_S           NUMBER(6,1)    NOT NULL,
  KOPF            VARCHAR2(80)   NOT NULL,
  TEXT            VARCHAR2(600)  NOT NULL,
  QUELLE_TEXT     VARCHAR2(200),
  SOURCE_ID       NUMBER(10),
  CONSTRAINT HEI_PANEL_PK PRIMARY KEY (PANEL_ID),
  CONSTRAINT HEI_PANEL_UK UNIQUE (SHOT_ID, VON_S),
  CONSTRAINT HEI_PANEL_ZEIT_CK CHECK (BIS_S > VON_S),
  CONSTRAINT HEI_PANEL_SHOT_FK FOREIGN KEY (SHOT_ID) REFERENCES HEI_SHOT (SHOT_ID) ON DELETE CASCADE,
  CONSTRAINT HEI_PANEL_SOURCE_FK FOREIGN KEY (SOURCE_ID) REFERENCES HEI_SOURCE (SOURCE_ID)
)
/

